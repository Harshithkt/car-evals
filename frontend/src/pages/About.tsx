import type { Metrics } from '../lib/api'
import { num, pct } from '../lib/format'
import { Plot } from '../components/Plot'
import { Card, PageHeader } from '../components/ui'

const STEPS: [string, string][] = [
  ['Classical preprocessing', 'Aspect-preserving resize, per-channel z-score, edges (Canny), morphology and contours give a classical vehicle ROI and hand-crafted features: HOG (shape), LBP/GLCM (texture), colour histograms and geometry (aspect ratio, symmetry, edge density).'],
  ['YOLOv8 vehicle localisation', 'A YOLOv8s detector fine-tuned on Stanford Cars boxes finds each vehicle. If it finds nothing, the pipeline falls back to the best low-confidence box, then the classical contour ROI, then the whole image.'],
  ['Illumination normalisation', 'Dark or washed-out crops get adaptive gamma correction plus CLAHE on the LAB lightness channel before classification.'],
  ['ConvNeXt-Tiny + flip TTA', 'An ImageNet-22k-pretrained ConvNeXt-Tiny, fine-tuned on padded vehicle crops (288 px), scores all 196 classes. Logits are averaged with a horizontally flipped copy (test-time augmentation).'],
  ['Late fusion with classical features', 'The classical features go through Standardise → PCA → logistic regression; the fused score is log softmax(z / T) + α · log p_classical.'],
  ['Temperature calibration', 'Temperatures T (deep) and T₂ (fused) are fitted on validation so the reported confidence matches the observed accuracy.'],
  ['Low-confidence handling', 'p(top-1) ≥ τ → confident make/model/year. Otherwise, if the summed make probability ≥ τ_make, the app reports the likely make and flags the model/year as uncertain; else it reports low confidence with the top candidates.'],
]

export default function About({ metrics, plots }: { metrics: Metrics | null; plots: string[] | null }) {
  const cal = metrics?.calibration_params
  const conf = metrics?.confidence
  const hyb = metrics?.approach_comparison && Object.entries(metrics.approach_comparison).find(([k]) => k.startsWith('Hybrid'))?.[1]
  return (
    <div className="space-y-5">
      <PageHeader eyebrow="About" title="About this system">
        P5: Intelligent Fine-Grained Vehicle Recognition and Analysis. Given a photo, the system localises each car and identifies its
        make, model and year among 196 Stanford Cars classes, using a hybrid of classical computer vision and deep learning.
      </PageHeader>

      {metrics?.requirements_summary && (
        <Card title="Requirement checklist" subtitle="Generated by the evaluation notebook from the measured results">
          <ul className="divide-y divide-grid">
            {Object.entries(metrics.requirements_summary).map(([req, res]) => (
              <li key={req} className="grid gap-1 py-2.5 sm:grid-cols-[16rem_1fr] sm:gap-4">
                <span className="flex items-start gap-2 text-sm font-medium text-ink">
                  <svg viewBox="0 0 24 24" className="mt-0.5 h-4 w-4 shrink-0 text-good-ink" fill="none" stroke="currentColor" strokeWidth="2" aria-hidden><path d="M20 6L9 17l-5-5" strokeLinecap="round" strokeLinejoin="round" /></svg>
                  {req}
                </span>
                <span className="text-[13px] leading-relaxed text-ink-2">{res}</span>
              </li>
            ))}
          </ul>
        </Card>
      )}

      <Card title="Hybrid pipeline">
        <ol className="space-y-3">
          {STEPS.map(([t, d], i) => (
            <li key={t} className="grid grid-cols-[2rem_1fr] gap-2">
              <span className="flex h-7 w-7 items-center justify-center rounded-full bg-accent-wash/60 text-sm font-semibold text-ink tabular">{i + 1}</span>
              <div>
                <div className="text-sm font-medium text-ink">{t}</div>
                <p className="text-[13px] text-ink-2">{d}</p>
              </div>
            </li>
          ))}
        </ol>
        {(cal || conf) && (
          <p className="mt-4 rounded-lg bg-surface-2 px-3 py-2 text-xs text-ink-2 tabular">
            Deployed parameters: T = {num(cal?.T, 3)} · α = {num(cal?.alpha, 2)} · T₂ = {num(cal?.T2, 3)} · τ = {num(conf?.tau, 2)} · τ_make = {num(conf?.tau_make, 2)}
            {hyb && <> · hybrid test top-1 {pct(hyb.top1)}, make accuracy {pct(hyb.make_acc)}</>}
          </p>
        )}
      </Card>

      <div className="grid gap-5 md:grid-cols-2">
        <Card title="Dataset">
          <p className="text-[13px] text-ink-2">
            Stanford Cars: 16,185 images of 196 classes at the make / model / year level (8,144 train, 8,041 test), with one bounding box per image.
            10% of the training images are held out for validation. Thresholds and temperatures are tuned on that split; all reported accuracies are on the unseen test set.
          </p>
        </Card>
        <Card title="Scope and constraints">
          <ul className="list-disc space-y-1 pl-4 text-[13px] text-ink-2">
            <li>The dataset has no number-plate annotations or video, so the system does <b>not</b> do licence-plate recognition or vehicle tracking.</li>
            <li>Only the 196 Stanford Cars classes (mostly 1990s–2012 US-market cars) can be recognised. Newer or unseen models get the closest known class, which is why the confidence handling matters.</li>
            <li>Grad-CAM is computed for the first detected vehicle only, and only with the PyTorch backend.</li>
          </ul>
        </Card>
      </div>

      <div className="grid gap-5 lg:grid-cols-2">
        <Plot name="eda_stats" title="Dataset statistics" available={plots} />
        <Plot name="augmentations" title="Training augmentations" caption="Illumination, viewpoint, occlusion and low-resolution augmentations" available={plots} />
      </div>
      <Plot name="eda_samples" title="Dataset samples" available={plots} />
    </div>
  )
}
